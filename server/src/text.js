export const MESSAGES = { en: EN, zh: ZH };

/** Pick the language: --lang, else the locale environment variables. */
export function pickLanguage(flag, env = process.env) {
  if (flag === 'zh' || flag === 'en') return flag;
  const loc = env.LC_ALL || env.LC_MESSAGES || env.LANG || '';
  return /^zh/i.test(loc) ? 'zh' : 'en';
}

/**
 * A text function for one language. Glyphs ({ok}, {bad}, {warn}, {dot}) and links ({extension},
 * {connect}) are filled in automatically; style() colours them when the terminal supports it.
 */
export function createText(lang, style = {}) {
  const table = MESSAGES[lang] ?? EN;
  const fixed = {
    ok: style.ok ?? '✓',
    bad: style.bad ?? '✗',
    warn: style.warn ?? '!',
    dot: style.dot ?? '·',
    ...LINKS[lang] ?? LINKS.en,
  };
  return (key, vars = {}) => {
    const s = table[key] ?? EN[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : k in fixed ? fixed[k] : m));
  };
}
